const BY_ID = new Map(RECIPES.map((recipe) => [recipe.id, recipe]));

export function getRecipe(id: string): Recipe | undefined {
  return BY_ID.get(id);
}

/** Best alias match for a free-text dish name, or null. */
export function findRecipeByName(name: string): Recipe | null {
  const needle = name.toLowerCase().trim();
  if (!needle) return null;

  let best: { recipe: Recipe; score: number } | null = null;
  for (const recipe of RECIPES) {
    for (const alias of [recipe.name.toLowerCase(), ...recipe.aliases]) {
      let score = 0;
      if (needle === alias) score = 100;
      else if (needle.includes(alias)) score = 60 + alias.length;
      else if (alias.includes(needle) && needle.length > 3) score = 40 + needle.length;
      if (score && (!best || score > best.score)) best = { recipe, score };
    }
  }
  return best ? best.recipe : null;
}

